import {readFileSync,mkdirSync,writeFileSync} from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..'),source=path.join(root,'public');
const read=name=>readFileSync(path.join(source,name),'utf8');
const data=(name,type)=>'data:'+type+';base64,'+readFileSync(path.join(source,name)).toString('base64');
const effects={};
for(const name of ['click_003.ogg','confirmation_002.ogg','back_001.ogg'])effects[name]=data('audio/'+name,'audio/ogg');
const strip=code=>code.replace(/^import .*?;\r?\n/gm,'').replace(/^export /gm,'');
let game=strip(read('game.mjs'));
game=game.replace("new URL('./assets/campus-original.jpg', import.meta.url).href",JSON.stringify(data('assets/campus-original.jpg','image/jpeg')));
game=game.replace("new URL('./audio/happy-adventure.mp3', import.meta.url).href",JSON.stringify(data('audio/happy-adventure.mp3','audio/mpeg')));
game=game.replace("fetch(new URL('./audio/'+file, import.meta.url))",'fetch(INLINE_EFFECTS[file])');
const code=[strip(read('engine.mjs')),strip(read('scores.mjs')),'const INLINE_EFFECTS='+JSON.stringify(effects)+';',game].join('\n');
if(/^import /m.test(code)||code.includes('import.meta.url'))throw new Error('Single-file export still has external module or media dependencies.');
let html=read('index.html');
html=html.replace('<link rel="stylesheet" href="./style.css">','<style>\n'+read('style.css')+'\n</style>');
html=html.replace('<script type="module" src="./game.mjs"></script>','<script type="module">\n'+code.replace(/<\/script/gi,'<\\/script')+'\n</script>');
const release=path.join(root,'release');mkdirSync(release,{recursive:true});
writeFileSync(path.join(release,'新生请说不-单文件试玩.html'),html);
console.log('Single-file game exported with original art, music, sound effects and local ranking.');
